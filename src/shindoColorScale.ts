// 震度しきい値バー(RealtimeIntensityThresholdBar)のグラデーション生成・
// スライダー可動域の算出に使うため、範囲の両端をエクスポートしておく。
export const MIN_INTENSITY = COLOR_STOPS[0][0];
export const MAX_INTENSITY = COLOR_STOPS[COLOR_STOPS.length - 1][0];

/**
 * 計測震度相当値(連続値)から表示色を求める。
 * 前後2点の線形補間で滑らかなグラデーションにする。
 * データが無い観測点向けの色はここでは扱わない(呼び出し側で別途分岐すること)。
 */
export function intensityToShindoColor(value: number): string {
  const clamped = Math.min(Math.max(value, MIN_INTENSITY), MAX_INTENSITY);

  // 0.1刻みなので、直接インデックス計算で最近傍2点を求められる
  // (COLOR_STOPS[0].v === MIN_INTENSITYが-3.0固定である前提)
  const rawIndex = (clamped - MIN_INTENSITY) / 0.1;
  const lowerIndex = Math.min(Math.floor(rawIndex), COLOR_STOPS.length - 2);
  const upperIndex = lowerIndex + 1;
  const lower = COLOR_STOPS[lowerIndex];
  const upper = COLOR_STOPS[upperIndex];

  const span = upper[0] - lower[0];
  const t = span === 0 ? 0 : (clamped - lower[0]) / span;

  const r = Math.round(lower[1] + (upper[1] - lower[1]) * t);
  const g = Math.round(lower[2] + (upper[2] - lower[2]) * t);
  const b = Math.round(lower[3] + (upper[3] - lower[3]) * t);

  return `rgb(${r}, ${g}, ${b})`;
}

/** データが無い/無効な観測点用の表示色(半透明グレー) */
export const NO_DATA_COLOR = "rgba(128,128,128,0.4)";
